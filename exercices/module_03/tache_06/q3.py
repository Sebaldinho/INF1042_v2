premiere_valeur = float(input("Entrez la première valeur décimale : "))
deuxieme_valeur = float(input("Entrez la deuxième valeur décimale : "))

produit = premiere_valeur * deuxieme_valeur
difference = premiere_valeur - deuxieme_valeur

print(f"Produit : {produit}")
print(f"Différence : {difference}")
